const directive = name => alias(new RegExp('#[ \t]*'+name), '#'+name)

// A source branch holds syntax, not a configuration decision.
function conditionalRules(suffix, content, repeatContent = true) {
  const body = $ => repeatContent ? repeat(content($)) : content($)
  return {
    ['preproc_if_'+suffix]: $ => seq(choice(seq(directive('if'), field('condition', $._preproc_expression), '\n'),
      seq(choice(directive('ifdef'), directive('ifndef')), field('name', $.identifier))),
      body($), optional(field('alternative', $['preproc_else_'+suffix])), directive('endif')),
    ['preproc_else_'+suffix]: $ => choice(
      seq(directive('else'), body($)),
      seq(directive('elif'), field('condition', $._preproc_expression), '\n', body($), optional(field('alternative', $['preproc_else_'+suffix])))),
  }
}

